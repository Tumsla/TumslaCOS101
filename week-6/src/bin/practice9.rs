// Practice 9: Relational
fn main() {
    let a = 10;
    let b = 20;

    let res = a > b;
    println!("{}", res);
    let res = a < b;
    println!("{}", res);
    let res = a >= b;
    println!("{}", res);
    let res = a <= b;
    println!("{}", res);
    let res = a == b;
    println!("{}", res);
    let res = a != b;
    println!("{}", res);
}
